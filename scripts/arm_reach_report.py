#!/usr/bin/env python3
"""Phase 9a: offline reach / mass / torque report for the arm design (config arm.yaml) -> markdown.

    python3 scripts/arm_reach_report.py [--out docs/results/data/phase9a/arm_reach.md]     # numpy + pyyaml, ~1 min

Grasp maps: object centre on a 1 cm grid in the body frame BEHIND the robot (robot standing, nominal stance), feasible =
object clear of the legs/body + an IK solution within the joint limits for one of the class's approach angles + grasp
AND pre-grasp (5 cm back along the approach) collision-free (capsule model, 5 mm margin). Robot yaw is free (the robot
turns its back to the object), so the maps are what the FINAL APPROACH must hit, not what Nav2 must hit.
"""
import argparse
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "gurdy_core"))

from gurdy_core import arm as A  # noqa: E402

DR = {"payload_kg": (0.0, 0.30), "payload_offset_m": 0.02, "body_mass_scale": (0.85, 1.15)}   # rl/envs/randomization.py


def grasp_map(a, rb, obj, xs, ys):
    gz = A.ground_z(rb)
    ok = np.zeros((len(ys), len(xs)), bool)
    for i, y in enumerate(ys):
        for j, x in enumerate(xs):
            ok[i, j] = A.object_clear_of_legs(rb, obj, (x, y)) and A.plan_grasp(a, rb, obj, (x, y), gz) is not None
    return ok


def inscribed(ok, xs, ys):
    """Largest disc (centre on the grid) fully inside the feasible set -> (radius, (x, y))."""
    pts_bad = np.array([(xs[j], ys[i]) for i in range(len(ys)) for j in range(len(xs)) if not ok[i, j]])
    best = (0.0, None)
    for i in range(len(ys)):
        for j in range(len(xs)):
            if ok[i, j]:
                r = float(np.min(np.hypot(pts_bad[:, 0] - xs[j], pts_bad[:, 1] - ys[i]))) if len(pts_bad) else math.inf
                edge = min(xs[j] - xs[0], xs[-1] - xs[j], ys[i] - ys[0], ys[-1] - ys[i])
                r = min(r, edge)
                if r > best[0]:
                    best = (r, (xs[j], ys[i]))
    return best


def disc_coverage(ok, xs, ys, c, R):
    inside = [(i, j) for i in range(len(ys)) for j in range(len(xs)) if math.hypot(xs[j] - c[0], ys[i] - c[1]) <= R]
    return sum(ok[i, j] for i, j in inside) / max(len(inside), 1)


def ascii_map(ok, xs, ys, step=2):
    rows = []
    for i in range(len(ys) - 1, -1, -step):
        rows.append(f"{ys[i]:+.2f} " + "".join("#" if ok[i, j] else "." for j in range(0, len(xs), step)))
    rows.append("      x: " + f"{xs[0]:+.2f} ... {xs[-1]:+.2f} (left = further behind the robot)")
    return "\n".join(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "docs/results/data/phase9a/arm_reach.md"))
    args = ap.parse_args()
    a, rb = A.load_all()
    L = []
    p = L.append
    p("# Phase 9a arm: offline reach / mass / torque report (generated by scripts/arm_reach_report.py)\n")

    # ---- mass and CoM
    base = A.robot_point_masses(rb)
    m0, c0 = A.com(base)
    p("## Mass and centre of mass (robot standing, nominal stance)\n")
    p("| configuration | total mass (kg) | added (kg) | CoM x / y / z (mm) | CoM shift xy (mm) | CoM rise (mm) | "
      "6-foot support margin (mm) | worst tripod margin (mm) |")
    p("|---|---|---|---|---|---|---|---|")
    cases = [("robot alone", None, 0.0), ("+ arm folded", "folded", 0.0),
             (f"+ arm folded + {a.payload_max:.2f} kg object", "folded", a.payload_max),
             ("+ arm ready (pre-grasp)", "ready", 0.0)]
    gz = A.ground_z(rb)
    worst_grasp = None
    for obj in A.PICKABLE.values():
        for x in np.arange(-0.40, -0.18, 0.02):
            r = A.plan_grasp(a, rb, obj, (x, 0.0), gz)
            if r:
                m, c = A.com(base + A.arm_point_masses(a, r[0], obj["mass"]))
                if worst_grasp is None or abs(c[0]) > abs(worst_grasp[1][0]):
                    worst_grasp = (r[0], c, obj["mass"])
    for name, pose, pay in cases:
        pts = base if pose is None else base + A.arm_point_masses(a, a.poses[pose], pay)
        m, c = A.com(pts)
        p(f"| {name} | {m:.3f} | {m - m0:.3f} | {c[0]*1e3:+.1f} / {c[1]*1e3:+.1f} / {c[2]*1e3:+.1f} | "
          f"{math.hypot(*(c[:2]-c0[:2]))*1e3:.1f} | {(c[2]-c0[2])*1e3:.1f} | {A.support_margin(rb, c[:2])*1e3:.0f} | "
          f"{A.tripod_margin(rb, c[:2])*1e3:.0f} |")
    if worst_grasp:
        q, c, pay = worst_grasp
        m = m0 + A.total_mass(a) + pay
        p(f"| + arm at the most rearward grasp found (standing, {pay:.2f} kg) | {m:.3f} | {m - m0:.3f} | "
          f"{c[0]*1e3:+.1f} / {c[1]*1e3:+.1f} / {c[2]*1e3:+.1f} | {math.hypot(*(c[:2]-c0[:2]))*1e3:.1f} | "
          f"{(c[2]-c0[2])*1e3:.1f} | {A.support_margin(rb, c[:2])*1e3:.0f} | {A.tripod_margin(rb, c[:2])*1e3:.0f} |")
    p(f"\nRL domain randomisation the walking policy was trained with (`rl/envs/randomization.py`): payload "
      f"{DR['payload_kg'][0]}-{DR['payload_kg'][1]} kg on the body at <= {DR['payload_offset_m']*1e3:.0f} mm xy offset "
      f"(at body height: CoM height was never randomised), body mass x{DR['body_mass_scale'][0]}-{DR['body_mass_scale'][1]}. "
      f"Arm {A.total_mass(a):.3f} kg + object <= {a.payload_max:.2f} kg = {A.total_mass(a)+a.payload_max:.3f} kg.\n")

    # ---- torques
    p("## Static gravity torque (worst case with the max payload)\n")
    poses = {"folded": a.poses["folded"], "ready": a.poses["ready"]}
    grasp_poses = []
    for obj in A.PICKABLE.values():
        for x in np.arange(-0.42, -0.16, 0.02):
            for y in np.arange(-0.10, 0.101, 0.05):
                r = A.plan_grasp(a, rb, obj, (x, y), gz)
                if r:
                    grasp_poses.append(r[0])
    p("| joint | servo class | rated (N·m) | folded | ready | worst feasible grasp | use of rating |")
    p("|---|---|---|---|---|---|---|")
    for j in ("arm_shoulder", "arm_elbow", "arm_wrist_pitch"):
        tf = A.joint_torques(a, poses["folded"], a.payload_max)[j]
        tr = A.joint_torques(a, poses["ready"], a.payload_max)[j]
        tg = max(A.joint_torques(a, q, a.payload_max)[j] for q in grasp_poses)
        p(f"| {j} | {a.raw['joints'][j]['servo']} | {a.effort[j]:.2f} | {tf:.3f} | {tr:.3f} | {tg:.3f} | "
          f"{100*max(tf, tr, tg)/a.effort[j]:.0f} % |")
    p(f"\n({len(grasp_poses)} feasible grasp poses checked. Dynamic torques and the gripper squeeze are not included.)\n")

    # ---- grasp maps
    xs = np.round(np.arange(-0.46, -0.149, 0.01), 3)
    ys = np.round(np.arange(-0.20, 0.201, 0.01), 3)
    p("## Where an object must be for a grasp (body frame, robot standing; object centre)\n")
    p("| object | size (m) | mass (kg) | strategy | feasible area (cm²) | x range at y=0 (m) | largest disc inside "
      "(radius cm, centre) | coverage of a 2 / 5 / 12 cm disc at that centre |")
    p("|---|---|---|---|---|---|---|---|")
    maps = {}
    for name, obj in A.PICKABLE.items():
        ok = grasp_map(a, rb, obj, xs, ys)
        maps[name] = ok
        area = ok.sum() * 1.0
        j0 = int(np.argmin(np.abs(ys)))
        xr = xs[ok[j0]]
        rad, c = inscribed(ok, xs, ys)
        size = obj.get("size") or (2 * obj["radius"], 2 * obj["radius"], obj["height"])
        cov = [disc_coverage(ok, xs, ys, c, R) for R in (0.02, 0.05, 0.12)] if c else [0, 0, 0]
        p(f"| {name} | {' x '.join(f'{v:.3f}' for v in size)} | {obj['mass']:.2f} | {obj['grasp']} | {area:.0f} | "
          f"{(f'{xr.min():+.2f} .. {xr.max():+.2f}' if len(xr) else '-')} | {rad*100:.1f}, ({c[0]:+.2f}, {c[1]:+.2f}) | "
          f"{' / '.join(f'{100*v:.0f} %' for v in cov)} |" if c else f"| {name} | - | - | - | 0 | - | - | - |")
    p("\nNav2 stops within 0.12 m (xy goal tolerance) and 0.2 rad: a 12 cm disc is NOT covered by any class, so a final "
      "approach (wrist camera + closed-loop relmotion, target error <= 2 cm) is required before every grasp.\n")
    for name, ok in maps.items():
        p(f"### {name}\n\n```\n{ascii_map(ok, xs, ys)}\n```\n")

    # ---- existing classes
    p("## Existing lab classes (semantic_lab / lab4)\n")
    p("| class | size (m) | est. real mass (kg) | verdict |")
    p("|---|---|---|---|")
    for name, o in A.EXISTING.items():
        why = []
        if min(o["size"][:2]) > a.width_max:
            why.append(f"narrowest side {min(o['size'][:2]):.2f} m > gripper {a.width_max:.2f} m")
        if o["mass_est"] > a.payload_max:
            why.append(f"~{o['mass_est']:.0f} kg > {a.payload_max:.2f} kg")
        p(f"| {name} | {' x '.join(f'{v:.2f}' for v in o['size'])} | {o['mass_est']:.1f} | TOO BIG: {'; '.join(why)} |")

    # ---- lidar
    bs = a.raw["mount"]["base"]["size"]
    d = abs(a.M[0]) - bs[0] / 2
    half = math.degrees(math.atan2(bs[1] / 2, d))
    p(f"\n## LiDAR\n\nThe yaw-servo base ({bs[0]:.2f} x {bs[1]:.2f} m, z {a.M[2]:.3f}-{a.M[2]+bs[2]:.3f} m) crosses the lidar "
      f"plane (z 0.05): it hides a rear sector of about +-{half:.0f} deg (inside the footprint, so scan_self_filter turns it "
      f"into 'no return'). Folded, every other arm part stays >= "
      f"{A.folded_ok(a, rb, a.poses['folded'], a.payload_max)[1]['lowest']*1e3 - 50:.0f} mm above the plane.\n")
    text = "\n".join(L) + "\n"
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(text)
    print(text)


if __name__ == "__main__":
    main()
