#!/usr/bin/env python3
"""CI: expand every robot xacro variant to URDF and check it is a valid kinematic tree (no ROS needed).

Variants: plain robot, Gazebo build (sensors + lidar + ros2_control), fixed base, arm, arm + MoveIt collision
proxies. For each: XML parses, unique link / joint names, every joint's parent and child exist, exactly one
root link, every link reachable from it (a tree), revolute / prismatic joints have <limit>, masses > 0.
`check_urdf` (liburdfdom-tools) is run too when it is installed (GitHub Actions installs it; the ROS image has it).

    python3 scripts/ci/check_urdf.py [--out DIR]     # --out: keep the expanded .urdf files
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

import xacro

ROOT = Path(__file__).resolve().parents[2]
DESC = ROOT / "ros2_ws/src/gurdy_description"
CFG = {"robot_yaml": str(DESC / "config/robot.yaml"), "arm_yaml": str(DESC / "config/arm.yaml")}
CTRL = "/tmp/gurdy_controllers.yaml"      # generated by sim.launch.py at launch; only a path string inside the URDF

VARIANTS = {
    "robot": ("gurdy.urdf.xacro", {}),
    "gazebo_lidar": ("gurdy.urdf.xacro", {"sim_gazebo": "true", "lidar": "true", "sensors": "true", "controllers_yaml": CTRL}),
    "fixed_base": ("gurdy.urdf.xacro", {"fixed_base": "true"}),
    "no_arm_wrapper": ("gurdy_with_arm.urdf.xacro", {}),
    "arm": ("gurdy_with_arm.urdf.xacro", {"arm": "true"}),
    "arm_gazebo": ("gurdy_with_arm.urdf.xacro", {"arm": "true", "sim_gazebo": "true", "lidar": "true", "controllers_yaml": CTRL}),
    "arm_moveit": ("gurdy_with_arm.urdf.xacro", {"arm": "true", "moveit_collision": "true"}),
}


def structural_errors(urdf: ET.Element) -> list[str]:
    errs: list[str] = []
    links = [l.get("name") for l in urdf.findall("link")]
    joints = urdf.findall("joint")
    for kind, names in (("link", links), ("joint", [j.get("name") for j in joints])):
        dup = sorted({n for n in names if names.count(n) > 1})
        if dup:
            errs.append(f"duplicate {kind} names {dup}")
    lset, children, parent_of = set(links), {}, {}
    for j in joints:
        p, c = j.find("parent"), j.find("child")
        if p is None or c is None:
            errs.append(f"joint {j.get('name')} lacks parent/child")
            continue
        p, c = p.get("link"), c.get("link")
        for end in (p, c):
            if end not in lset:
                errs.append(f"joint {j.get('name')} refers to missing link {end!r}")
        if c in parent_of:
            errs.append(f"link {c} has two parent joints")
        parent_of[c] = p
        children.setdefault(p, []).append(c)
        if j.get("type") in ("revolute", "prismatic") and j.find("limit") is None:
            errs.append(f"joint {j.get('name')} ({j.get('type')}) has no <limit>")
    roots = [l for l in links if l not in parent_of]
    if len(roots) != 1:
        errs.append(f"expected one root link, got {roots}")
    else:
        seen, todo = set(), [roots[0]]
        while todo:
            n = todo.pop()
            if n in seen:
                errs.append(f"cycle at {n}")
                break
            seen.add(n)
            todo += children.get(n, [])
        if seen != lset:
            errs.append(f"links not reachable from {roots[0]}: {sorted(lset - seen)}")
    for m in urdf.iter("mass"):
        if not float(m.get("value", "nan")) > 0:
            errs.append(f"non-positive mass {m.get('value')}")
    return errs


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    a = ap.parse_args()
    out = Path(a.out) if a.out else Path(tempfile.mkdtemp(prefix="ci_urdf_"))
    out.mkdir(parents=True, exist_ok=True)
    check_urdf = shutil.which("check_urdf")
    bad = 0
    for name, (fname, args) in VARIANTS.items():
        try:
            doc = xacro.process_file(str(DESC / "urdf" / fname), mappings={**CFG, **args})
            text = doc.toprettyxml(indent="  ")
            urdf = ET.fromstring(text)
        except Exception as e:  # noqa: BLE001 - any expansion error is a CI failure
            print(f"URDF FAIL {name}: xacro/XML: {type(e).__name__}: {e}")
            bad += 1
            continue
        errs = structural_errors(urdf)
        f = out / f"{name}.urdf"
        f.write_text(text)
        if check_urdf:
            r = subprocess.run([check_urdf, str(f)], capture_output=True, text=True)
            if r.returncode != 0 or "Successfully Parsed XML" not in r.stdout:
                errs.append("check_urdf: " + (r.stderr or r.stdout).strip().splitlines()[-1])
        n_links, n_joints = len(urdf.findall("link")), len(urdf.findall("joint"))
        if errs:
            bad += 1
            for e in errs:
                print(f"URDF FAIL {name}: {e}")
        else:
            print(f"urdf ok  {name:<15} {n_links} links {n_joints} joints")
    print(f"urdf: {len(VARIANTS) - bad}/{len(VARIANTS)} variants OK (check_urdf {'run' if check_urdf else 'NOT installed: structural checks only'})")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
