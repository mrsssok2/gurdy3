#!/usr/bin/env python3
"""Generate `lab4_vln` (VLN demos, 2026-11-28): the lab4 world UNCHANGED (walls, doors, 10 big objects, room names) + ONE chair
in room D (the kitchen), so "go to the kitchen, past the chair, stop near the red barrel" has a real chair to pass.

    python3 scripts/gen_world_lab4_vln.py            # writes worlds/lab4_vln.sdf (+ meshes), maps/lab4_vln.places.yaml,
                                                     # docs/results/data/lab4_vln/lab4_vln_gt.json
    python3 scripts/gen_world_lab4_vln.py --check    # exit 1 if the committed files are out of date

lab4.* and lab4_fetch.* are not touched (the overnight fetch runs use lab4_fetch). The chair is appended to lab4's object list
inside this process only, so lab4's own placement rules (>= 0.3 m + radius from walls, >= 0.9 m + radius from doorway centres,
>= 0.8 m from other objects and the spawn) validate it.
The chair is NOT in the saved lab4 map (maps/lab4_map.yaml, reused): Nav2 sees it only through the live lidar (its legs) in the
costmaps; the global plan from the static map can run through it until the costmap marks it.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "gurdy_core"))
sys.path.insert(0, str(ROOT / "scripts"))
import gen_world_lab4 as L4  # noqa: E402

OUT_SDF = L4.WORLDS / "lab4_vln.sdf"
OUT_PLACES = ROOT / "maps/lab4_vln.places.yaml"
OUT_GT = ROOT / "docs/results/data/lab4_vln/lab4_vln_gt.json"

# (name, class, x, y, yaw, variant, color): off the door B-D -> red barrel line, 1.3-1.9 m from the other room-D objects
CHAIR = ("chair_d", "chair", 4.3, 3.9, 0.9, {"rgb": [0.35, 0.22, 0.10]}, "")


def with_chair():
    if CHAIR not in L4.OBJECTS:
        L4.OBJECTS = list(L4.OBJECTS) + [CHAIR]


def build():
    with_chair()
    sdf, places, gt = L4.build()
    sdf = sdf.replace('<world name="lab4">', '<world name="lab4_vln">').replace(
        "GENERATED by scripts/gen_world_lab4.py - edit the script, not this file.",
        "GENERATED by scripts/gen_world_lab4_vln.py (lab4 + one chair in room D) - edit the script, not this file.")
    places = places.replace("map_id: lab4", "map_id: lab4_vln").replace(
        "# Named places for the lab4 world", "# Named places for the lab4_vln world (= lab4 + a chair in room D; same walls, lab4 map reusable)").replace(
        "GENERATED by scripts/gen_world_lab4.py", "GENERATED by scripts/gen_world_lab4_vln.py")
    gt = gt.replace('"world": "lab4"', '"world": "lab4_vln"', 1)
    return sdf, places, gt


if __name__ == "__main__":
    with_chair()
    errs = L4.validate()
    if errs:
        print("\n".join(errs)); sys.exit(2)
    sdf, places, gt = build()
    pairs = [(OUT_SDF, sdf), (OUT_PLACES, places), (OUT_GT, gt)]
    if "--check" in sys.argv:
        sys.exit(0 if all(p.exists() and p.read_text() == t for p, t in pairs) else 1)
    for p, t in pairs:
        p.parent.mkdir(parents=True, exist_ok=True); p.write_text(t)
        print(f"wrote {p}")
